const fs=require('node:fs');
const path=require('node:path');
const crypto=require('node:crypto');
const assert=require('node:assert/strict');
const root=process.argv[2]||'verified';
const read=n=>fs.readFileSync(path.join(root,n));
const txt=n=>read(n).toString('utf8').trim();
const hash=n=>crypto.createHash('sha256').update(read(n)).digest('hex');
const names=['photon16.wasm','SOURCE_COMMIT','SOURCE_INDEX','RUST_TOOLCHAIN','NODE_VERSION','REPRODUCTION','QUALIFICATION','BROWSER_ACCEPTANCE.json','browser-rust.png'];
const source=txt('SOURCE_COMMIT');
assert.match(source,/^[0-9a-f]{40}$/);
assert.equal(source,process.env.GITHUB_SHA,'source commit mismatch');
const binary=hash('photon16.wasm');
const reproduction=txt('REPRODUCTION').split(/\r?\n/);
assert.deepEqual(reproduction,['build-a '+binary,'build-b '+binary]);
const expected=['native-tests=PASS','wasm-verifier=PASS','same-runner-reproduction=PASS','browser-acceptance=PASS'];
assert.deepEqual(txt('QUALIFICATION').split(/\r?\n/),expected);
const e=JSON.parse(txt('BROWSER_ACCEPTANCE.json'));
assert.equal(e.sourceCommit,source);assert.equal(e.wasmSha256,binary);
assert.ok(e.servedHashes.length>=3&&e.servedHashes.every(h=>h===binary));
assert.deepEqual(e.errors,[]);assert.deepEqual(e.failed,[]);
assert.equal(e.native.codons,552960);assert.equal(e.native.storage.returns,2880);assert.equal(e.native.storage.conservation,true);
assert.equal(e.trials.candidates.length,4);assert.ok(e.trials.candidates.every(r=>r.digest===e.trials.winner.digest&&Number.isFinite(r.cost)&&r.cost>=e.trials.winner.cost));
assert.equal(e.online.trace.length,96);assert.equal(e.online.trace[0].budget,1536);
assert.ok(e.online.trace.every((r,i)=>r.t===i&&[0,448,1536,1984].includes(r.budget)&&Number.isFinite(r.idle)&&r.idle>=0&&r.idle<=r.budget));
const manifest=Object.fromEntries(txt('RELEASE_SHA256SUMS').split(/\r?\n/).map(line=>{const m=line.match(/^([0-9a-f]{64})  ([A-Za-z0-9_.-]+)$/);assert.ok(m,'invalid checksum line');return [m[2],m[1]];}));
assert.deepEqual(Object.keys(manifest).sort(),[...names].sort());
for(const n of names)assert.equal(hash(n),manifest[n],n+' checksum mismatch');
const report={schema:'photon16-release-adjudication-v1',sourceCommit:source,wasmSha256:binary,manifestSha256:hash('RELEASE_SHA256SUMS'),status:'STAGED_BUNDLE_PASS',liveDeployment:'UNVERIFIED',independentWitness:'UNVERIFIED'};
fs.writeFileSync(path.join(root,'ADJUDICATION.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report));
