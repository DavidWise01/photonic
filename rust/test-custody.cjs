'use strict';
const assert=require('node:assert/strict'),crypto=require('node:crypto');
const {replay,payload,head}=require('./custody-registry.cjs');
const make=()=>{const k=crypto.generateKeyPairSync('ed25519');return {privateKey:k.privateKey,publicKey:k.publicKey.export({type:'spki',format:'pem'})};};
const cust=make(),a=make(),b=make(),rot=make();
const anchor={ancestry:'synthetic-custodian',publicKey:cust.publicKey};
const roots=['repository-ci'];
const sign=(k,e)=>crypto.sign(null,payload(e),k.privateKey).toString('base64');
const genesis='0'.repeat(64);
function event(previous,sequence,action,id,ancestry,k,old){const e={previous,sequence,action,id,ancestry,publicKey:k.publicKey,custodyDigest:'a'.repeat(64)};e.custodianSignature=sign(cust,e);e.possessionSignature=sign(k,e);if(old)e.previousSignature=sign(old,e);return e;}
const e1=event(genesis,1,'ENROLL','W1','root1',a),e2=event(head(e1),2,'ENROLL','W2','root2',b),e3=event(head(e2),3,'ROTATE','W1','root1',rot,a),e4=event(head(e3),4,'REVOKE','W2','root2',b);
const chain=[e1,e2,e3,e4],checkpoint=head(e4);
const good=replay(chain,anchor,roots,checkpoint);
assert.equal(good.registry.length,1);assert.equal(good.registry[0].publicKey,rot.publicKey);assert.equal(good.releaseAuthority,'HOLD');
const reject=(name,fn)=>{assert.throws(fn,undefined,name);console.log('REJECTED '+name);};
reject('missing anchor',()=>replay(chain,null,roots,checkpoint));
reject('producer custodian',()=>replay(chain,{...anchor,ancestry:'repository-ci'},roots,checkpoint));
reject('rollback',()=>replay(chain.slice(0,3),anchor,roots,checkpoint));
reject('reordered events',()=>replay([e2,e1,e3,e4],anchor,roots,checkpoint));
reject('changed custody digest',()=>replay([{...e1,custodyDigest:'b'.repeat(64)},...chain.slice(1)],anchor,roots,checkpoint));
const bad=(name,e)=>reject(name,()=>replay([e1,e],anchor,roots,head(e)));
bad('producer witness',event(head(e1),2,'ENROLL','W2','repository-ci',b));
bad('duplicate root',event(head(e1),2,'ENROLL','W2','root1',b));
bad('duplicate key',event(head(e1),2,'ENROLL','W2','root2',a));
bad('wrong old rotation key',event(head(e1),2,'ROTATE','W1','root1',rot,b));
bad('wrong ancestry rotation',event(head(e1),2,'ROTATE','W1','root2',rot,a));
const replayKey=event(checkpoint,5,'ROTATE','W1','root1',a,rot);
reject('retired key reuse',()=>replay([...chain,replayKey],anchor,roots,head(replayKey)));
const revoked=event(checkpoint,5,'ROTATE','W2','root2',make(),b);
reject('revoked identity rotation',()=>replay([...chain,revoked],anchor,roots,head(revoked)));
console.log('SYNTHETIC ONLY: custody lifecycle control and 12 rejection scenarios. No external custody established.');
